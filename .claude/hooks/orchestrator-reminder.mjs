#!/usr/bin/env node
// UserPromptSubmit: короткое напоминание о manager-style дисциплине в контекст каждого хода.
//
// Правило объёма (2026-07-28): это УКАЗАТЕЛЬ, а не копия правил. Инъекция уходит в каждый
// промпт пользователя, включая «привет» и «что дальше», поэтому здесь только то, что
// меняет первый шаг ответа: кто я в этой сессии, что спросить до старта, что делегировать,
// что требует approval, какая дизайн-система по умолчанию. Всё остальное — в `CLAUDE.md`,
// он и так грузится в начале сессии целиком.
//
// Прежняя версия (~1900 знаков) перечисляла команды приёмки, путь к компонентам shadcn и
// историю архивации Figma-индексов — это дублировало §6.1 и раздувало каждый ход.
// Список типов работы обязан совпадать с `CLAUDE.md` §0.1.
process.stdout.write(
  "[Оркестрация] Главная сессия = оркестратор. Классифицируй тип работы " +
  "(full product / reference-driven / quick draft / limited engineering / cleanup / external write). " +
  "Для продуктового run оси берутся у человека, а не угадываются: спроси про образец для сверки и покажи план работ, " +
  "из правки которого выводится масштаб — молчаливый выбор = process_deviation (CLAUDE.md §0.2). " +
  "Нетривиальную дизайн-, DS- и сборочную работу делегируй профильному субагенту через Agent tool; " +
  "финальный ответ pipeline собирает ТОЛЬКО оркестратор. " +
  "Внешние записи (Notion / Figma / deploy / git commit / push) — после явного approval. " +
  "Дизайн-система по умолчанию — shadcn/ui в коде, витрина Storybook, приёмка машинная (CLAUDE.md §6.1). " +
  "Гейты человека исполняешь ТЫ, субагент показать не может: 7.5 макеты (если носитель Figma), " +
  "8.5a витрина до сборки страницы, 8.5b собранная страница — показ со ссылкой и ожиданием замечаний, " +
  "запись `human_review:` в ledger, проверяется валидатором. «Делай дальше» гейт не закрывает. " +
  "Правила — CLAUDE.md, детальные gates — agent-pack/workflows/claude-operating-rules.md."
);
process.exit(0);
